"""Fit per-weapon action models from verified hub debug Stroke lines.

Name each debug session <action>_<speed>_<weapon>, for example
vertical_slow_spear. Omit speed for non-actions. The optional _train suffix
means the same thing; _val sessions are optional and only used for an offline
check. Record at least eight repetitions per action/speed and one of each
non-action for every weapon.
"""

import argparse
import csv
import os
import re
from datetime import date

import pandas as pd

import numpy as np

from figpipe import debug_fit as D
from figpipe import raw
from figpipe import replay as R
from figpipe.logs import FAKE_ACTIONS, REAL_ACTIONS

SKETCHES = [os.path.join("2 players", f"p{p}_right_wrist", f"p{p}_right_wrist.ino") for p in (1, 2)]
BEGIN = "// ===== STRIKE_MODEL — BEGIN (generated by fit_strike_model.py, don't hand-edit) ====="
END = "// ===== STRIKE_MODEL — END ====="
BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
ENUM = {w: "WEAPON_" + w.upper() for w in raw.WEAPONS}
LOCK_RE = re.compile(r"(?:weapon_locked=|Active weapon=)(sword_shield|spear|mace)\b")
SPEEDS = ("slow", "normal", "fast")
MIN_STRIKES = 8
OVERRIDE_FILE = "weapon_grip_overrides.csv"


def read_grip_overrides(logs_dir):
    """Explicit physical-grip attestations for sessions logged under a wrong lock."""
    path = os.path.join(logs_dir, OVERRIDE_FILE)
    if not os.path.exists(path):
        return {}
    out = {}
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            name = row.get("debug_file", "").strip()
            physical = row.get("physical_weapon", "").strip()
            logged = row.get("logged_locked_weapon", "").strip()
            note = row.get("attestation", "").strip()
            if (not name.startswith("debug_") or not name.endswith(".csv") or
                    os.path.basename(name) != name or physical not in raw.WEAPONS or
                    logged not in raw.WEAPONS or physical == logged or not note or name in out):
                raise ValueError(f"{path}: invalid or duplicate grip override for {name!r}")
            out[name] = (physical, logged)
    return out


def verified_weapon(session, overrides=None):
    if not session.weapon or session.label not in REAL_ACTIONS + FAKE_ACTIONS:
        raise ValueError(f"{session.name}: filename needs action and weapon labels")
    debug_path = session.path
    if os.path.basename(debug_path).startswith("raw_"):
        debug_path = os.path.join(os.path.dirname(debug_path), "debug_" + os.path.basename(debug_path)[4:])
    if not os.path.exists(debug_path):
        raise ValueError(f"{session.name}: matching debug CSV is missing")
    with open(debug_path, newline="", encoding="utf-8") as f:
        observed = {m.group(1) for row in csv.DictReader(f)
                    for m in LOCK_RE.finditer(row.get("line", ""))}
    name = os.path.basename(debug_path)
    override = (overrides or {}).get(name)
    if observed != {session.weapon} and override != (session.weapon, next(iter(observed), None)):
        raise ValueError(f"{session.name}: label {session.weapon!r} conflicts with locked-weapon log {sorted(observed)}")
    if override and (observed != {override[1]} or session.weapon != override[0] or observed == {session.weapon}):
        raise ValueError(f"{session.name}: grip override conflicts with filename or locked-weapon log")
    session.locked_weapon = next(iter(observed))
    return session.weapon


def validate_coverage(sessions, rep):
    errors = []
    for w in raw.WEAPONS:
        group = [s for s in sessions if s.weapon == w and s.split == "train"]
        for action in REAL_ACTIONS:
            for speed in SPEEDS:
                matches = [s for s in group if s.label == action and s.speed == speed]
                n = len(rep[(rep.session.isin([s.name for s in matches])) &
                            (rep.role == "strike") & ~rep.has_gap.astype(bool) &
                            (rep.kind == ("push" if action == "thrust" else "rot"))])
                if not matches or n < MIN_STRIKES:
                    errors.append(f"{w}/train/{action}/{speed}: {n} usable strikes, need {MIN_STRIKES}")
        for fake in FAKE_ACTIONS:
            if not any(s.label == fake for s in group):
                errors.append(f"{w}/train/{fake}: missing non-action session")
    if errors:
        raise ValueError("insufficient recording coverage:\n  " + "\n  ".join(errors))


def fit(logs_dir):
    sessions, lines = D.load_captures(logs_dir)
    if not sessions:
        raise ValueError("no labeled hub debug action sessions found")
    overrides = read_grip_overrides(logs_dir)
    available = {os.path.basename(s.path) for s in sessions}
    unused = set(overrides) - available
    if unused:
        raise ValueError(f"grip overrides have no training debug session: {sorted(unused)}")
    for s in sessions:
        verified_weapon(s, overrides)
    if overrides:
        print(f"Accepted {len(overrides)} attested grip overrides; logged lock retained for diagnostics.")
    if len({s.name for s in sessions}) != len(sessions):
        raise ValueError("duplicate session timestamps; record players in separate runs")
    rep, warnings = D.stroke_rows(sessions, lines)
    rep = D.label_roles(rep)
    if warnings:
        print(f"Hub debug log warnings: {len(warnings)} incomplete candidate/feature groups; "
              "individual complete Stroke lines remain usable.")
        for message in warnings[:5]:
            print("  " + message)
    print(parity_report(rep))
    validate_coverage(sessions, rep)
    models = {}
    for w in raw.WEAPONS:
        train = rep[(rep.weapon == w) & (rep.split == "train")].copy()
        strike = R.fit_templates(R.strikes_for_fit(train))
        if set(strike.action) != set(REAL_ACTIONS) - {"thrust"}:
            raise ValueError(f"{w}: strike templates incomplete")
        strike["weapon"] = w
        old_model, old_limit, old_thrust, old_thrust_limit = R.model_from_sketch(SKETCHES[0], w)
        old_reach = R.reach_limit_from_sketch(SKETCHES[0], w)
        limit = tune_strike_limit(train, strike, old_model, old_limit)
        thrust = R.fit_thrust(R.thrusts_for_fit(train, min_reach=0.15))
        if thrust is None:
            raise ValueError(f"{w}: thrust template missing")
        reach, thrust_limit = tune_thrust_limits(
            train, strike, limit, thrust, old_model, old_limit, old_thrust, old_thrust_limit, old_reach)
        models[w] = (strike, limit, thrust, thrust_limit, reach)
    return models, sessions, rep


def parity_report(rep):
    """Compare re-scored logged features with the hub's recorded distances."""
    with open(SKETCHES[0], encoding="utf-8") as f:
        if "verified hub debug sessions" in f.read():
            return ("Logged-score parity skipped: the current sketch was generated after "
                    "some of these sessions, so its scores are not their logged baseline.")
    lines = []
    for w in raw.WEAPONS:
        model, _, thrust, _ = R.model_from_sketch(SKETCHES[0], w)
        g = rep[rep.locked_weapon == w]
        diffs = []
        rot = g[g.kind == "rot"]
        if len(rot):
            score = R.distances(rot, model)
            same = score.nearest.to_numpy() == rot.logged_nearest.to_numpy()
            diffs.extend(abs(score.dist.to_numpy()[same] - rot.logged_dist.to_numpy()[same]))
        push = g[g.kind == "push"]
        if len(push) and thrust:
            score = R.thrust_distances(push, thrust)
            diffs.extend(abs(score.dist.to_numpy() - push.logged_dist.to_numpy()))
        lines.append(f"{w}: logged-score median error={np.median(diffs):.3f}, "
                     f"p95={np.percentile(diffs, 95):.3f} ({len(diffs)} comparable strokes)")
    return "Logged feature parity: " + "; ".join(lines)


def tune_strike_limit(rep, model, old_model, old_limit):
    rot = rep[rep.kind == "rot"]
    old = R.decide(rot, old_model, old_limit)
    old_fake = int((old[(old.cls == "fake")].accept).sum())
    best, best_score = None, -np.inf
    for limit in np.arange(1.0, 8.01, 0.25):
        dec = R.decide(rot, model, float(limit))
        fake = dec[dec.cls == "fake"]
        if int(fake.accept.sum()) > old_fake:
            continue
        positive = dec[(dec.role == "strike") & (dec.label != "thrust") & ~dec.has_gap]
        other = dec[(dec.cls == "real") & (dec.role != "strike") & ~dec.has_gap]
        score = (float(positive.accept.mean()) if len(positive) else 0) - (
            float(other.accept.mean()) if len(other) else 0)
        if score > best_score:
            best, best_score = float(limit), score
    if best is None:
        raise ValueError("no strike limit keeps non-action accepts at the current count")
    return best


def tune_thrust_limits(rep, model, strike_limit, thrust, old_model, old_limit,
                       old_thrust, old_thrust_limit, old_reach):
    baseline = R.decide(rep, old_model, old_limit, thrust=old_thrust,
                        thrust_max=old_thrust_limit, thrust_min_reach=old_reach)
    old_fake = int(baseline[(baseline.kind == "push") & (baseline.cls == "fake")].accept.sum())
    best, best_score = None, -np.inf
    for reach in (0.15, 0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50,
                  0.60, 0.75, 1.00, 1.25):
        for limit in np.arange(0.5, 5.01, 0.25):
            dec = R.decide(rep, model, strike_limit, thrust=thrust,
                           thrust_max=float(limit), thrust_min_reach=reach)
            push = dec[dec.kind == "push"]
            fake = push[push.cls == "fake"]
            if int(fake.accept.sum()) > old_fake:
                continue
            positive = push[(push.role == "strike") & ~push.has_gap]
            other = push[(push.role != "strike") & ~push.has_gap]
            score = (float(positive.accept.mean()) if len(positive) else 0) - (
                float(other.accept.mean()) if len(other) else 0)
            if score > best_score:
                best, best_score = (reach, float(limit)), score
    if best is None:
        raise ValueError("no thrust reach/distance pair keeps non-action accepts at the current count")
    return best


def c_block(models, session_names, override_count=0):
    f = lambda v: f"{v:.4f}f"
    note = f" ({override_count} attested physical-grip overrides)" if override_count else ""
    lines = [BEGIN,
             f"// Fitted {date.today().isoformat()} from {len(session_names)} verified hub debug sessions{note}.",
             "const StrikeTemplate STRIKE_MODEL[] = {",
             "    // weapon, action, axis ux,uy,uz, axisSpreadDeg, push px,py,pz, pushSpreadDeg,",
             "    // rotMeanDeg, rotSpreadDeg, torsoRef, torsoSpread, bidirectional"]
    for w in raw.WEAPONS:
        model, _, _, _, _ = models[w]
        for _, m in model.iterrows():
            lines.append(f'    {{{ENUM[w]}, "{m.action}", {f(m.ux)}, {f(m.uy)}, {f(m.uz)}, {f(m.axis_spread)}, '
                         f'{f(m.px)}, {f(m.py)}, {f(m.pz)}, {f(m.push_spread)}, {f(m.rot_mean)}, {f(m.rot_spread)}, '
                         f'{f(m.torso_ref)}, {f(m.torso_spread)}, {"true" if m.bidirectional else "false"}}},')
    lines += ["};", "const int STRIKE_MODEL_COUNT = sizeof(STRIKE_MODEL) / sizeof(STRIKE_MODEL[0]);",
              "const WeaponActionLimits ACTION_LIMITS[] = {"]
    for w in raw.WEAPONS:
        _, limit, _, thrust_limit, min_reach = models[w]
        lines.append(f"    {{{ENUM[w]}, {f(limit)}, {f(thrust_limit)}, {f(min_reach)}}},")
    lines += ["};", "const WeaponThrustTemplate THRUST_MODEL[] = {"]
    for w in raw.WEAPONS:
        t = models[w][2]
        lines.append(f"    {{{ENUM[w]}, {{{f(t['ux'])}, {f(t['uy'])}, {f(t['uz'])}, {f(t['dir_spread'])}, "
                     f"{f(t['reach_mean'])}, {f(t['reach_spread'])}, {f(t['rot_ref'])}, {f(t['rot_spread'])}}}}},")
    lines += ["};", END]
    return "\n".join(lines)


def validation_report(models, sessions, rep):
    if not any(s.split == "val" for s in sessions):
        return "No validation sessions supplied; check the fitted model in live play."
    lines = []
    for w in raw.WEAPONS:
        names = [s.name for s in sessions if s.weapon == w and s.split == "val"]
        if not names:
            continue
        val = rep[rep.session.isin(names)].copy()
        if val.empty:
            lines.append(f"{w:13} validation sessions contained no detected strokes")
            continue
        model, limit, thrust, thrust_limit, min_reach = models[w]
        dec = R.mark_hits(R.decide(val, model, limit, thrust=thrust,
                                   thrust_max=thrust_limit, thrust_min_reach=min_reach))
        valid = dec[~dec.has_gap.astype(bool)]
        old_model, old_limit, old_thrust, old_thrust_limit = R.model_from_sketch(SKETCHES[0], w)
        old = R.mark_hits(R.decide(val, old_model, old_limit, thrust=old_thrust,
                                  thrust_max=old_thrust_limit,
                                  thrust_min_reach=R.reach_limit_from_sketch(SKETCHES[0], w)))
        old = old[~old.has_gap.astype(bool)]
        for act in REAL_ACTIONS:
            for speed in SPEEDS:
                kind = "push" if act == "thrust" else "rot"
                g = valid[(valid.label == act) & (valid.speed == speed) &
                          (valid.role == "strike") & (valid.kind == kind)]
                old_g = old[(old.label == act) & (old.speed == speed) &
                            (old.role == "strike") & (old.kind == kind)]
                lines.append(f"{w:13} {act:11} {speed:6} detected={int(g.hit.sum())}/{len(g)} "
                             f"(flashed model: {int(old_g.hit.sum())}/{len(old_g)})")
        false = valid[(valid.cls == "fake") & valid.accept.astype(bool)]
        old_false = old[(old.cls == "fake") & old.accept.astype(bool)]
        lines.append(f"{w:13} non-actions accepted={len(false)} (flashed model: {len(old_false)})")
        between = valid[(valid.cls == "real") & (valid.role != "strike") & valid.accept.astype(bool)]
        old_between = old[(old.cls == "real") & (old.role != "strike") & old.accept.astype(bool)]
        lines.append(f"{w:13} other strokes accepted={len(between)} (flashed model: {len(old_between)})")
        misses = valid[(valid.role == "strike") & ~valid.hit.astype(bool)]
        lines.append(f"{w:13} missed stroke reasons={misses.reason.value_counts().to_dict()}")
        far = misses[misses.reason == "far"]
        if len(far):
            components = {c: round(float(far[c].abs().median()), 2)
                          for c in ("d_axis", "d_push", "d_rot", "d_torso", "d_reach")
                          if far[c].notna().any()}
            lines.append(f"{w:13} far-miss median distance components={components}")
            confusion = far[(far.kind == "rot") & (far.nearest != far.label)]
            if len(confusion):
                lines.append(f"{w:13} far-miss nearest-action confusions="
                             f"{confusion.groupby(['label', 'nearest']).size().to_dict()}")
    return "\n".join(lines)


def training_report(models, rep):
    """Direct logged-stroke checks; these are training data, not validation."""
    lines = []
    for w in raw.WEAPONS:
        train = rep[(rep.weapon == w) & (rep.split == "train")]
        model, limit, thrust, thrust_limit, min_reach = models[w]
        current, old_limit, old_thrust, old_thrust_limit = R.model_from_sketch(SKETCHES[0], w)
        new = R.decide(train, model, limit, thrust=thrust, thrust_max=thrust_limit,
                       thrust_min_reach=min_reach)
        old = R.decide(train, current, old_limit, thrust=old_thrust,
                       thrust_max=old_thrust_limit,
                       thrust_min_reach=R.reach_limit_from_sketch(SKETCHES[0], w))
        lines.append(f"{w}: distance limits strike={limit:.2f}, thrust={thrust_limit:.2f}, "
                     f"min thrust reach={min_reach:.2f} m")
        for action in REAL_ACTIONS:
            kind = "push" if action == "thrust" else "rot"
            for speed in SPEEDS:
                mask = ((new.label == action) & (new.speed == speed) &
                        (new.role == "strike") & (new.kind == kind) & ~new.has_gap)
                n, o = new[mask], old[mask]
                new_ok = n.accept & (n.nearest == action)
                old_ok = o.accept & (o.nearest == action)
                lines.append(f"  {action:10} {speed:6}: {int(new_ok.sum())}/{len(n)} "
                             f"(current {int(old_ok.sum())}/{len(o)})")
                if (~new_ok).any():
                    missed = n[~new_ok]
                    reasons = missed.reason.value_counts().to_dict()
                    nearest = missed.nearest.value_counts(dropna=False).to_dict()
                    lines.append(f"    misses: {reasons}; nearest: {nearest}")
                    far = missed[missed.reason == "far"]
                    if len(far):
                        components = {c: round(float(far[c].abs().median()), 2)
                                      for c in ("d_axis", "d_push", "d_rot", "d_torso", "d_reach")
                                      if far[c].notna().any()}
                        lines.append(f"    far distance components: {components}")
        for tag, dec in (("fitted", new), ("current", old)):
            fake = dec[dec.cls == "fake"]
            lines.append(f"  {tag} non-action accepts: {int(fake.accept.sum())}/{len(fake)}")
    return "\n".join(lines)


def write_sketches(block):
    updated = []
    for path in SKETCHES:
        with open(path, encoding="utf-8", newline="") as fh:
            src = fh.read()
        if len(BLOCK_RE.findall(src)) != 1:
            raise ValueError(f"{path}: expected exactly one generated model block")
        nl = "\r\n" if "\r\n" in src else "\n"
        updated.append((path, BLOCK_RE.sub(lambda _: block.replace("\n", nl), src, count=1)))
    for path, src in updated:
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(src)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--logs", default=os.path.join("2 players", "logs"))
    ap.add_argument("--write", action="store_true", help="write verified model into both hub sketches")
    args = ap.parse_args()
    models, sessions, rep = fit(args.logs)
    override_count = int(rep.loc[rep.weapon != rep.locked_weapon, "session"].nunique())
    block = c_block(models, [s.name for s in sessions], override_count)
    print(block)
    print("\nRecorded-data training check:\n" + training_report(models, rep))
    print("\nValidation:\n" + validation_report(models, sessions, rep))
    if args.write:
        write_sketches(block)
        print("Wrote both hub sketches")


if __name__ == "__main__":
    main()
