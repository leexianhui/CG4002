"""Fits the hub's STRIKE_MODEL table (strike templates + distance limit) from
RAW_STREAM sessions and prints it as C, or writes it into the hub sketches.

    python fit_strike_model.py [--logs "2 players/logs"] [--write]

--write replaces the block between the STRIKE_MODEL BEGIN/END markers in
both hub sketches (p1 and p2). Refit after new recordings or after changing
how the board is strapped on. See figpipe/replay.py for the method.
"""

import argparse
import os
import re
from datetime import date

import pandas as pd

from figpipe import raw
from figpipe import replay as R

SKETCHES = [os.path.join("2 players", f"p{p}_right_wrist", f"p{p}_right_wrist.ino") for p in (1, 2)]
BEGIN = "// ===== STRIKE_MODEL — BEGIN (generated by fit_strike_model.py, don't hand-edit) ====="
END = "// ===== STRIKE_MODEL — END ====="
BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def fit(logs_dir):
    """(model, limit, thrust, thrust_limit, session names) from every labelled
    RAW_STREAM session (sessions without a known action label are skipped)."""
    table, sessions, _ = raw.build_table(logs_dir)
    sessions = [s for s in sessions if s.label is not None]
    rep = R.label_strokes(pd.concat([R.replay_session(s) for s in sessions], ignore_index=True), table)
    model = R.fit_templates(R.strikes_for_fit(rep))
    limit = R.tune_max_dist(rep, table, model)
    thrust = R.fit_thrust(R.thrusts_for_fit(rep))
    thrust_limit = R.tune_thrust_dist(rep, model, limit, thrust)
    return model, limit, thrust, thrust_limit, sorted(s.name for s in sessions)


def c_block(model, limit, thrust, thrust_limit, session_names):
    f = lambda v: f"{v:.4f}f"
    t = thrust
    lines = [BEGIN,
             f"// Fitted {date.today().isoformat()} from {len(session_names)} RAW_STREAM sessions "
             f"({session_names[0][:15]} .. {session_names[-1][:15]}),",
             "// strikes of every speed. One shared row per action (all weapons); thrust is",
             "// matched by its push (THRUST_MODEL), not by rotation.",
             "const StrikeTemplate STRIKE_MODEL[] = {",
             "    // weapon, action, axis ux,uy,uz, axisSpreadDeg, push px,py,pz, pushSpreadDeg,",
             "    // rotMeanDeg, rotSpreadDeg, torsoRef, torsoSpread, bidirectional"]
    for _, m in model.iterrows():
        lines.append(f'    {{WEAPON_UNKNOWN, "{m.action}", {f(m.ux)}, {f(m.uy)}, {f(m.uz)}, {f(m.axis_spread)}, '
                     f'{f(m.px)}, {f(m.py)}, {f(m.pz)}, {f(m.push_spread)}, {f(m.rot_mean)}, {f(m.rot_spread)}, '
                     f'{f(m.torso_ref)}, {f(m.torso_spread)}, {"true" if m.bidirectional else "false"}}},')
    lines += ["};",
              "const int STRIKE_MODEL_COUNT = sizeof(STRIKE_MODEL) / sizeof(STRIKE_MODEL[0]);",
              f"const float STRIKE_MAX_DIST = {limit:g}; // nearest-template distance limit",
              "// push direction ux,uy,uz, dirSpreadDeg, reachMeanM, reachSpreadM, rotRefDeg, rotSpreadDeg",
              f"const ThrustTemplate THRUST_MODEL = {{{f(t['ux'])}, {f(t['uy'])}, {f(t['uz'])}, {f(t['dir_spread'])}, "
              f"{f(t['reach_mean'])}, {f(t['reach_spread'])}, {f(t['rot_ref'])}, {f(t['rot_spread'])}}};",
              f"const float THRUST_MAX_DIST = {thrust_limit:g}; // thrust-template distance limit",
              END]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--logs", default=os.path.join("2 players", "logs"))
    ap.add_argument("--write", action="store_true", help="write the table into both hub sketches")
    args = ap.parse_args()
    block = c_block(*fit(args.logs))
    print(block)
    if args.write:
        for path in SKETCHES:
            with open(path, encoding="utf-8", newline="") as fh:
                src = fh.read()
            nl = "\r\n" if "\r\n" in src else "\n"
            if not BLOCK_RE.search(src):
                raise SystemExit(f"{path}: STRIKE_MODEL markers not found")
            src = BLOCK_RE.sub(lambda _: block.replace("\n", nl), src, count=1)
            with open(path, "w", encoding="utf-8", newline="") as fh:
                fh.write(src)
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
